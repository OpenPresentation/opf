#!/usr/bin/env node
// NT-12: `pnpm report:native-coverage [--tier smoke|release|full] [--out <file.md>] [--json]` prints what the native-test
// corpus covers: units per tier against the totals, units on exactly one slide, decks that add no unit of their own,
// schema locations no deck shows, and per tier the files, slides and modeled application minutes. Generated on demand
// from the repository; not committed.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyze, readLists } from './coverage.mjs';
import { computeUnits, loadInputs, TIERS } from './units.mjs';

const KINDS = ['schema', 'feature', 'known', 'script', 'variant'];
const KIND_NAMES = { schema: 'schema locations', feature: 'manifest features', known: 'known differences with places', script: 'scripts of the text', variant: 'export variants' };
const minutes = (value) => value.toFixed(1);

/** The report as Markdown. `tiers` limits the per-tier parts (all tiers when empty). */
export function formatReport(analysis, { tiers = TIERS } = {}) {
  const lines = ['# Native-test corpus coverage', '', 'Generated by `pnpm report:native-coverage` from the repository (no application). Units: see `docs/native-testing.md`, "Coverage and budgets".', ''];
  lines.push('## Units covered', '', `| Unit | Total | ${tiers.join(' | ')} |`, `| --- | --- | ${tiers.map(() => '---').join(' | ')} |`);
  for (const kind of KINDS) lines.push(`| ${KIND_NAMES[kind]} | ${analysis.totals[kind] ?? 0} | ${tiers.map((tier) => analysis.tiers[tier].covered[kind] ?? 0).join(' | ')} |`);
  lines.push('', 'The schema total is every countable location of `spec/schemas/opf.schema.json` plus the default layouts; the other totals are what the manifest and `known/` name (scripts and variants: what the corpus shows).', '');

  lines.push('## Time per tier', '', '| Tier | Files | Slides | Parts | Not modeled | Modeled minutes (budget) |', '| --- | --- | --- | --- | --- | --- |');
  for (const tier of tiers) {
    const figures = analysis.tiers[tier];
    const parts = figures.size.parts.map((part) => `${part.name} ${part.files}/${part.slides}`).join(', ');
    const time = Object.entries(figures.time)
      .map(([application, { minutes: value, budgetMinutes }]) => `${application} ${minutes(value)}${budgetMinutes === null ? '' : ` (${budgetMinutes})`}`)
      .join(', ');
    lines.push(`| ${tier} | ${figures.size.files} | ${figures.size.slides} | ${parts} | ${figures.size.notModeled.join(', ') || 'none'} | ${time} |`);
  }
  lines.push('', 'Parts are files/slides. A source without decks in the repository (languages) or that depends on the release (native-fragments) is not modeled.', '');

  lines.push('## Decks with no unit of their own', '');
  for (const tier of tiers) {
    const decks = analysis.tiers[tier].dominated;
    lines.push(`- ${tier}: ${decks.length ? decks.join(', ') : 'none'}`);
  }
  lines.push('', 'Within the tier, no schema location, script or variant that another deck of the tier lacks. In the whole corpus, a known record or a feature naming the deck lets it stay:', '');
  for (const { deck, namedBy } of analysis.dominated) lines.push(`- ${deck}: ${namedBy.length ? `named by ${namedBy.length} (${namedBy.slice(0, 4).join(', ')}${namedBy.length > 4 ? ', ...' : ''})` : 'named by nothing (dominated-decks.json)'}`);
  lines.push('');

  lines.push(`## Schema locations no corpus deck shows (${analysis.gaps.length})`, '');
  if (analysis.gaps.length === 0) lines.push('None.');
  for (const gap of analysis.gaps) lines.push(`- ${gap.kind} ${gap.location}: ${gap.reason ?? 'not allowlisted'}`);
  lines.push('');

  const byKind = {};
  for (const { unit } of analysis.single) byKind[unit.slice(0, unit.indexOf(':'))] = (byKind[unit.slice(0, unit.indexOf(':'))] ?? 0) + 1;
  lines.push(`## Units on exactly one slide (${analysis.single.length})`, '', `By kind: ${Object.entries(byKind).map(([kind, count]) => `${kind} ${count}`).join(', ')}. Editing that slide can lose the unit; a second slide makes it safe.`, '');
  const byPlace = new Map();
  for (const { unit, place } of analysis.single) byPlace.set(place, [...(byPlace.get(place) ?? []), unit]);
  for (const [place, units] of byPlace) lines.push(`- ${place.replace('#', ' slide ')}: ${units.join('; ')}`);
  lines.push('');
  return lines.join('\n');
}

function main(argv) {
  const value = (flag) => {
    const at = argv.indexOf(flag);
    return at >= 0 ? argv[at + 1] : undefined;
  };
  const tier = value('--tier');
  if (tier !== undefined && !TIERS.includes(tier)) throw new Error(`--tier: use ${TIERS.join(', ')}`);
  const inputs = loadInputs();
  const analysis = analyze(computeUnits(inputs), inputs, readLists().budgets);
  const text = argv.includes('--json') ? `${JSON.stringify(analysis, null, 2)}\n` : formatReport(analysis, { tiers: tier ? [tier] : TIERS });
  const out = value('--out');
  if (out) {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  } else process.stdout.write(text);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
