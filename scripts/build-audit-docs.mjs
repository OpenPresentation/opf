// RR-29: keep the rule reference of docs/audit.md in step with the audit rule registry.
//
//   node scripts/build-audit-docs.mjs            rewrite the generated rule reference in docs/audit.md
//   node scripts/build-audit-docs.mjs --check    fail when docs/audit.md differs from a fresh render (drift)
//
// The prose of docs/audit.md is authored; only the block between the two markers is generated from
// `auditRules` (packages/javascript/src/audit*.ts), so a rule cannot be added, renamed or re-severitied
// without its documentation changing in the same commit.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = path.join(ROOT, 'docs', 'audit.md');
const START = '<!-- audit-rules:start (generated by scripts/build-audit-docs.mjs; do not edit by hand) -->';
const END = '<!-- audit-rules:end -->';

const names = { accessibility: 'Accessibility', design: 'Design', content: 'Content' };

/** The generated rule reference: one summary table and one section per rule, grouped by category. */
export function renderRuleReference(rules, thresholds) {
	const lines = [START, '', '| Rule | Severity | Category | What it reports |', '| --- | --- | --- | --- |'];
	for (const rule of rules) lines.push(`| [\`${rule.id}\`](#${rule.id.replace('/', '')}) | ${rule.severity} | ${names[rule.category]} | ${rule.summary} |`);
	for (const category of ['accessibility', 'design', 'content']) {
		lines.push('', `## ${names[category]} rules`, '');
		for (const rule of rules.filter((r) => r.category === category)) {
			lines.push(`### \`${rule.id}\``, '', `Default severity: **${rule.severity}**. ${rule.summary}`, '', `**Why.** ${rule.rationale}`, '');
			if (rule.standard) lines.push(`**Standard.** ${rule.standard}`, '');
			if (rule.thresholds?.length) lines.push(`**Thresholds.** ${rule.thresholds.map((t) => `\`${t}\` (default ${thresholds[t]})`).join(', ')}`, '');
			if (rule.approximations) lines.push(`**Approximations.** ${rule.approximations}`, '');
		}
	}
	lines.push(END);
	return lines.join('\n');
}

async function main() {
	const { auditRules, DEFAULT_AUDIT_THRESHOLDS } = await import(pathToFileURL(path.join(ROOT, 'packages', 'javascript', 'dist', 'audit.js')).href);
	const current = readFileSync(DOC, 'utf8');
	const start = current.indexOf(START.slice(0, 24)),
		end = current.indexOf(END);
	if (start < 0 || end < 0) throw new Error('docs/audit.md lacks the audit-rules markers.');
	const next = current.slice(0, start) + renderRuleReference(auditRules, DEFAULT_AUDIT_THRESHOLDS) + current.slice(end + END.length);
	if (process.argv.includes('--check')) {
		if (next.replace(/\r\n/g, '\n') !== current.replace(/\r\n/g, '\n')) {
			console.error('docs/audit.md is out of date. Run: node scripts/build-audit-docs.mjs');
			process.exit(1);
		}
		console.log('docs/audit.md rule reference is current.');
		return;
	}
	writeFileSync(DOC, next);
	console.log('Wrote docs/audit.md rule reference.');
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) await main();
