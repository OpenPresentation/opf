// RR-29, RR-55: keep the rule reference of docs/validate.md in step with the rule registry.
//
//   node scripts/build-validate-docs.mjs            rewrite the generated rule reference in docs/validate.md
//   node scripts/build-validate-docs.mjs --check    fail when docs/validate.md differs from a fresh render (drift)
//
// The prose of docs/validate.md is authored; only the block between the two markers is generated from
// `validationRules` (packages/javascript/src/validation-rules.ts and rules-*.ts), so a rule cannot be added, renamed,
// recategorised or re-severitied without its documentation changing in the same commit.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = path.join(ROOT, 'docs', 'validate.md');
const START = '<!-- validate-rules:start (generated by scripts/build-validate-docs.mjs; do not edit by hand) -->';
const END = '<!-- validate-rules:end -->';

const names = {
	format: 'Format',
	references: 'References',
	policy: 'Policy',
	accessibility: 'Accessibility',
	layout: 'Layout',
	content: 'Content',
};
const asks = {
	format: 'Is it well-formed OPF?',
	references: 'Does everything it points at resolve?',
	policy: "Does it follow the host's house rules?",
	accessibility: 'Can everyone read it?',
	layout: 'Will it present as authored?',
	content: 'Is anything left unfinished?',
};

/** The generated rule reference: one summary table, then one section per rule grouped by category. */
export function renderRuleReference(rules, thresholds) {
	const lines = [START, '', '| Rule | Category | Default | Cost | What it reports |', '| --- | --- | --- | --- | --- |'];
	for (const rule of rules) lines.push(`| [\`${rule.id}\`](#${rule.id.replace('/', '')}) | ${names[rule.category]} | ${rule.severity} | ${rule.cost} | ${rule.summary} |`);
	for (const category of Object.keys(names)) {
		const group = rules.filter((r) => r.category === category);
		if (!group.length) continue;
		lines.push('', `## ${names[category]} rules`, '', `*${asks[category]}*`, '');
		for (const rule of group) {
			lines.push(`### \`${rule.id}\``, '', `Default severity: **${rule.severity}**. Cost: ${rule.cost}. ${rule.summary}`, '', `**Why.** ${rule.rationale}`, '');
			if (rule.standard) lines.push(`**Basis.** ${rule.standard}`, '');
			if (rule.thresholds?.length) lines.push(`**Thresholds.** ${rule.thresholds.map((t) => `\`${t}\` (default ${thresholds[t]})`).join(', ')}`, '');
			if (rule.approximations) lines.push(`**Approximations.** ${rule.approximations}`, '');
		}
	}
	lines.push(END);
	return lines.join('\n');
}

async function main() {
	const { validationRules, DEFAULT_VALIDATION_THRESHOLDS } = await import(pathToFileURL(path.join(ROOT, 'packages', 'javascript', 'dist', 'index.js')).href);
	const current = readFileSync(DOC, 'utf8');
	const start = current.indexOf(START.slice(0, 24)),
		end = current.indexOf(END);
	if (start < 0 || end < 0) throw new Error('docs/validate.md lacks the validate-rules markers.');
	const next = current.slice(0, start) + renderRuleReference(validationRules, DEFAULT_VALIDATION_THRESHOLDS) + current.slice(end + END.length);
	if (process.argv.includes('--check')) {
		if (next.replace(/\r\n/g, '\n') !== current.replace(/\r\n/g, '\n')) {
			console.error('docs/validate.md is out of date. Run: node scripts/build-validate-docs.mjs');
			process.exit(1);
		}
		console.log('docs/validate.md rule reference is current.');
		return;
	}
	writeFileSync(DOC, next);
	console.log('Wrote docs/validate.md rule reference.');
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) await main();
