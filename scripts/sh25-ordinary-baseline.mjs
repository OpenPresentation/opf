import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const [repositoryArgument,authoredArgument,outputArgument,expectedRevision]=process.argv.slice(2);
assert.ok(repositoryArgument&&authoredArgument&&outputArgument&&expectedRevision,'usage: node sh25-ordinary-baseline.mjs <clean-repository> <authored-controls.json> <fresh-output.json> <expected-revision>');
assert.match(expectedRevision,/^[a-f0-9]{40}$/);
const repository=fs.realpathSync(repositoryArgument),output=path.resolve(outputArgument);
const git=args=>execFileSync('git',args,{cwd:repository,encoding:'utf8',windowsHide:true}).trim();
assert.equal(git(['rev-parse','HEAD']),expectedRevision);assert.equal(git(['status','--porcelain']),'');assert.ok(!fs.existsSync(output));
const authoredBytes=fs.readFileSync(authoredArgument),authored=JSON.parse(authoredBytes);assert.equal(authored.cases.length,32);
const {toSvg}=await import(pathToFileURL(path.join(repository,'packages/render/test/catalog-harness.mjs')).href);
const {toPptx}=await import(pathToFileURL(path.join(repository,'packages/pptx/test/helpers/default-catalog.mjs')).href);
const hash=value=>createHash('sha256').update(value).digest('hex'),cases=[];
for(const {id,deck} of authored.cases)cases.push({id,deck,svgSha256:hash(toSvg(deck,1)),pptxSha256:hash(await toPptx(deck))});
assert.equal(git(['status','--porcelain']),'');
fs.writeFileSync(output,JSON.stringify({source:expectedRevision,dirty:false,node:process.version,authoredTemplate:{path:path.resolve(authoredArgument),sha256:hash(authoredBytes),scope:'Authored ordinary control decks only; no historical output hash reused'},cases},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({source:expectedRevision,cases:cases.length,output,sha256:hash(fs.readFileSync(output))}));
