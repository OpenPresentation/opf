import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {pathToFileURL, fileURLToPath} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
assert.equal(process.versions.node.split('.')[0], '24');
const root = path.dirname(fileURLToPath(import.meta.url));
const fixture = JSON.parse(await readFile(path.join(root, 'font-edit-fixture-generator-02/generation.json'), 'utf8'));
const binding = fixture.bindings['@openpresentation/opf-pptx'];
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
assert.equal(sha(await readFile(binding.entry)), binding.entrySha256);
assert.equal(sha(await readFile(path.join(root, 'registry-consumer/package-lock.json'))), fixture.registryLockSha256);
const {fromPptx} = await import(pathToFileURL(binding.entry).href);
const pptxPath = path.join(root, 'native-font-edit-01/native-font-edit.pptx');
const bytes = await readFile(pptxPath), diagnostics = [];
const document = await fromPptx(bytes, {onDiagnostic: value => diagnostics.push(value)});
const output = path.join(root, 'font-semantic-reimport-01');
await mkdir(output);
await writeFile(path.join(output, 'reimport.opf.json'), JSON.stringify(document, null, 2) + '\n');
const plain = value => typeof value === 'string' ? value : Array.isArray(value) ? value.map(plain).join('') : value && typeof value === 'object' ? plain(value.text) : '';
const exact = document.slides?.length === 1 && plain(document.slides[0].title) === 'Gate E - Carlito' && plain(document.slides[0].text) === 'Regular 18 | Bold 20 | Italic 22 | BoldItalic 24';
await writeFile(path.join(output, 'comparison.json'), JSON.stringify({passed: exact, node: process.version, sourcePptxSha256: sha(bytes), registryLockSha256: fixture.registryLockSha256, binding, diagnostics, scope: 'Current title/body text from registry fromPptx. No physical-font identity, rich-style reconstruction, embedding or layout-fidelity acceptance.'}, null, 2) + '\n');
console.log(JSON.stringify({passed: exact, slideCount: document.slides?.length, title: document.slides?.[0]?.title, text: document.slides?.[0]?.text, diagnostics}));
assert.ok(exact, 'Retain actual reimport and comparison when current text differs.');
