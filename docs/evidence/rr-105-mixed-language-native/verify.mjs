import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import {pathToFileURL} from 'node:url';
const args=Object.fromEntries(Array.from({length:(process.argv.length-2)/2},(_,i)=>[process.argv[2+i*2],process.argv[3+i*2]]));
for(const name of ['--consumer','--suite','--saved','--route','--out'])assert.ok(args[name],name+' required');
assert.ok(['measured','native'].includes(args['--route']));
const consumer=path.resolve(args['--consumer']),suite=path.resolve(args['--suite']);
const manifest=JSON.parse(await fs.readFile(path.join(suite,'manifest.json'),'utf8'));
assert.equal(execFileSync('git',['-C',consumer,'rev-parse','HEAD'],{encoding:'utf8'}).trim(),manifest.consumerCommit,'consumer source moved');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
for(const [rel,expected]of Object.entries(manifest.sourceFiles))assert.equal(hash(await fs.readFile(path.join(consumer,rel))),expected,'consumer bytes changed: '+rel);
for(const [name,artifact]of Object.entries(manifest.artifacts))assert.equal(hash(await fs.readFile(path.join(suite,name))),artifact.sha256,'suite artifact changed: '+name);
const original=await fs.readFile(path.join(suite,args['--route']+'.pptx'));
assert.equal(hash(original),manifest.artifacts[args['--route']+'.pptx'].sha256,'original native input changed');
const bytes=await fs.readFile(path.resolve(args['--saved']));
const load=rel=>import(pathToFileURL(path.join(consumer,rel)).href);
const [{fromPptx},{gallery}]=await Promise.all([load('packages/pptx/dist/index.js'),load('packages/gallery/dist/index.js')]);
const require=createRequire(path.join(consumer,'packages/pptx/package.json')),{unzipSync,strFromU8}=require('fflate');
const parts=unzipSync(new Uint8Array(bytes));
const diagnostics=[],deck=await fromPptx(bytes,{catalogs:[gallery],onDiagnostic:d=>diagnostics.push(d)});
assert.equal(deck.slides.length,2);
const tag=value=>typeof value==='string'?value:value?.bcp47;
assert.equal(tag(deck.language),'en-US');
assert.equal(tag(deck.slides[1].language),'ar-SA','saved-copy import changed the Arabic slide language');
const runs=value=>Array.isArray(value)?value.flatMap(runs):value&&typeof value==='object'?[...(typeof value.text==='string'?[value]:[]),...Object.values(value).filter(x=>typeof x==='object').flatMap(runs)]:[];
const checked=[];
for(const expected of manifest.expectations){
 const xml=strFromU8(parts['ppt/slides/slide'+expected.slide+'.xml']);
 const normalized=text=>text.replace(/\s+/gu,' ').trim();
 const native=[...xml.matchAll(/<a:r>[\s\S]*?<\/a:r>/g)].map(m=>m[0]).filter(run=>new RegExp('lang="'+expected.language+'"').test(run));
 const text=native.flatMap(run=>[...run.matchAll(/<a:t>([\s\S]*?)<\/a:t>/g)].map(m=>m[1])).join(' ');
 assert.ok(normalized(text).includes(normalized(expected.nativeText??expected.text)),'saved native XML lost proofing language for '+expected.text);
 const imported=runs(deck.slides[expected.slide-1]).filter(run=>run.lang===expected.language).map(run=>run.text).join(' ');
 assert.ok(normalized(imported).includes(normalized(expected.text)),'import lost explicit run language: '+expected.text);
 checked.push({...expected,nativeXml:true,import:true,altLang:native.some(run=>/altLang=/.test(run))});
}
const report={schema:'opf-mixed-language-native-result/v1',scope:'Saved-file semantic verification; the coordinator attests the Office save step.',consumerCommit:manifest.consumerCommit,route:args['--route'],originalSha256:hash(original),savedSha256:hash(bytes),checked,diagnostics,passed:true};
await fs.writeFile(path.resolve(args['--out']),JSON.stringify(report,null,2)+'\n',{flag:'wx'});console.log(JSON.stringify(report,null,2));
