import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url)), consumer=path.join(root,'registry-consumer');
assert.equal(process.versions.node.split('.')[0],'24');
const require=createRequire(path.join(consumer,'package.json'));
const {unzipSync}=require('fflate'),{XMLValidator}=require('fast-xml-parser');
const sha=b=>createHash('sha256').update(b).digest('hex');
const parse=b=>JSON.parse(b.toString('utf8').replace(/^\uFEFF/,''));
const read=p=>readFile(path.join(root,p));
const gen=parse(await read('notes-order-registry-01/manifest.json'));
const entry=gen.cases.find(c=>c.id==='notes-control');
const pairs={original:await read('notes-order-registry-01/original/notes-control.pptx'),reordered:await read('notes-order-registry-01/reordered/notes-control.pptx')};
const original=unzipSync(pairs.original),reordered=unzipSync(pairs.reordered);
assert.equal(sha(pairs.original),entry.originalSha256);assert.equal(sha(pairs.reordered),entry.reorderedSha256);
assert.deepEqual(Object.keys(original).sort(),Object.keys(reordered).sort());
const changed=Object.keys(original).filter(p=>sha(original[p])!==sha(reordered[p]));
assert.deepEqual(changed,['ppt/presentation.xml']);
for(const archive of [original,reordered])for(const [name,b] of Object.entries(archive))if(/\.(xml|rels)$/.test(name))assert.equal(XMLValidator.validate(Buffer.from(b).toString('utf8')),true,name);
const xmlA=Buffer.from(original['ppt/presentation.xml']).toString(),xmlB=Buffer.from(reordered['ppt/presentation.xml']).toString();
assert.equal(xmlA.replace(/(<p:sldIdLst>[\s\S]*?<\/p:sldIdLst>)(<p:notesMasterIdLst>[\s\S]*?<\/p:notesMasterIdLst>)/,'$2$1'),xmlB);
const {fromPptx}=await import(gen.converterModule);
const importA=await fromPptx(pairs.original),importB=await fromPptx(pairs.reordered);
assert.deepEqual(importA,importB);
const prod=parse(await read('notes-production-native-01/report.json'));
const failed=parse(await read('notes-reordered-native-01/report.json'));
assert.equal(prod.cleanupConfirmed,true);assert.equal(prod.error,null);
assert.equal(failed.officeOperationsStopped,true);assert.equal(failed.cleanupConfirmed,false);
assert.match(failed.error,/0x80070570/);
const savedBytes=await readFile(prod.saved.path);assert.equal(sha(savedBytes),prod.saved.sha256);
const savedImport=await fromPptx(savedBytes),source=parse(await read('notes-order-registry-01/notes-control.opf.json'));
assert.equal(savedImport.slides.length,source.slides.length);
for(let i=0;i<source.slides.length;i++){
 assert.equal(savedImport.slides[i].notes,source.slides[i].notes);
 assert.equal(savedImport.slides[i].title,source.slides[i].title);
 assert.deepEqual(savedImport.slides[i].blocks,importA.slides[i].blocks);
}
const result={passed:true,node:process.version,verifierSha256:sha(await readFile(fileURLToPath(import.meta.url))),converterModule:gen.converterModule,converterEntrypointSha256:sha(await readFile(fileURLToPath(gen.converterModule))),lockSha256:sha(await readFile(path.join(consumer,'package-lock.json'))),sourcePair:entry,changedParts:changed,originalOrder:'sldIdLst then notesMasterIdLst',controlledOrder:'notesMasterIdLst then sldIdLst',production:{nativeLifecycle:'pass',savedSha256:prod.saved.sha256,currentNotesTitlesAndBody:'pass',cleanupConfirmed:true},reordered:{nativeLifecycle:'refused',call:'Presentations.Open',hresult:'0x80070570',cleanupConfirmed:false,timeout:false},conclusion:'Retain production ordering. Both archives parse and import identically offline, but only the current production control passed native open/save/close/reopen. Refusal is observed for this controlled file; it does not isolate all packaging versus XML-order causes or establish universal Office behavior. No retry was performed.'};
await writeFile(path.join(root,'notes-order-comparison.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
