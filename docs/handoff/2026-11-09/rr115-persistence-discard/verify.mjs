import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { gunzipSync } from 'node:zlib';
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const manifest = JSON.parse(readFileSync(new URL('./manifest.json', import.meta.url)));
const receipt = JSON.parse(readFileSync(new URL('./receipt.json', import.meta.url)));
const archive = readFileSync(new URL(manifest.archive, import.meta.url));
assert.equal(archive.length, manifest.bytes);
assert.equal(hash(archive), manifest.sha256);
const files = JSON.parse(gunzipSync(archive, { maxOutputLength: 2 * 1024 * 1024 })).files;
assert.equal(files.length, manifest.files.length);
const lookup = new Map(); let total = 0;
for (const [index, file] of files.entries()) {
  assert.ok(file.file.startsWith('artifacts/rr115/') && !file.file.split('/').includes('..'));
  const bytes = Buffer.from(file.data, 'base64');
  assert.deepEqual({ file: file.file, bytes: bytes.length, sha256: hash(bytes) }, manifest.files[index]);
  assert.ok(!lookup.has(file.file)); lookup.set(file.file, bytes); total += bytes.length;
}
const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim();
assert.equal(git('rev-parse', receipt.source + '^{tree}'), receipt.sourceTree);
for (const binding of receipt.bindings) assert.equal(git('rev-parse', receipt.source + ':' + binding.file), binding.gitBlob);
assert.deepEqual(receipt.runtimeChangedPaths, ['packages/editor/src/persistence-ui.js', 'packages/editor/src/persistence.js']);
assert.equal(receipt.typesKeysVersionsUnchanged, true);
assert.equal(receipt.protectedInputsUnchanged, true);
const log = (name) => lookup.get('artifacts/rr115/' + name).toString('utf8');
assert.match(log('discard-before.log'), /pass 0/); assert.match(log('discard-before.log'), /fail 5/);
assert.match(log('discard-after.log'), /pass 5/); assert.match(log('discard-after.log'), /fail 0/);
assert.match(log('persistence-existing.log'), /RR-22 persistence: ok/);
assert.match(log('ui-before.log'), /false discard must leave the real offer visible/);
assert.match(log('ui-after.log'), /UI discard after PASS/);
assert.match(log('release-report-contract.log'), /RR-113/); assert.match(log('release-report-contract.log'), /RR-114/);
assert.match(log('release-report-contract.log'), /fail 1/);
const ui = JSON.parse(lookup.get('artifacts/rr115/ui-after/receipt.json'));
assert.equal(ui.status, 'PASS'); assert.deepEqual(ui.requests, []); assert.deepEqual(ui.errors, []);
assert.equal(ui.sourceUiSha256, receipt.bindings.find((binding) => binding.file.endsWith('/persistence-ui.js')).workingSha256);
for (const name of ['ui-before/failed-discard.png', 'ui-after/failed-discard.png', 'ui-after/successful-retry.png']) assert.equal(lookup.get('artifacts/rr115/' + name).subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
const burndown = git('show', receipt.source + ':docs/programs/release-readiness/burndown.md');
const row = burndown.split('\n').find((line) => line.startsWith('| RR-115 |'));
assert.ok(row); assert.equal(row.split('|').length, 8); assert.match(row, /\| review \|/);
assert.equal(receipt.partialDeletion.multiKeyAtomicity, false);
assert.equal(receipt.nativeAcceptance, false);
console.log(JSON.stringify({ status: 'PASS', records: files.length, bytes: total, source: receipt.source, newPublicControls: 5, priorPersistenceSuite: 'PASS', uiProbe: 'PASS', originalFailuresPreserved: true, reportContractRedPreserved: true, maintainedFullBrowser: 'UNRUN', aggregate: 'BATCHED_NOT_RUN', nativeAcceptance: false }));
