const base=git('merge-base',...parents),b=read(base),ours=read(parents[0]),theirs=read(parents[1]);
const row=theirs.split('\n').find(line=>line.startsWith('| RR-115 |'));assert.ok(row);assert.ok(!ours.includes('| RR-115 |'));
const without=theirs.replace(row+'\n','');assert.ok(without.startsWith(b));const tail=without.slice(b.length);
const anchor=ours.split('\n').find(line=>line.startsWith('| RR-116 |'));assert.ok(anchor);
const expected=ours.replace(anchor,row+'\n'+anchor)+tail,actual=read(merge);assert.equal(actual,expected);
assert.equal(actual.replace(row+'\n','').slice(0,-tail.length),ours);
const proof=JSON.parse(fs.readFileSync(new URL('./performance-burndown-merge.json',import.meta.url)));
const hash=s=>createHash('sha256').update(s).digest('hex');
for(const [key,value]of Object.entries({base:b,ours,incoming:theirs,result:actual}))assert.equal(hash(value),proof[key]);
