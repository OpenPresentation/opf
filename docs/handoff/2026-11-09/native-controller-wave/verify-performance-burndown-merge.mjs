import {createHash} from 'node:crypto';
const file='docs/programs/release-readiness/burndown.md',merge='2d9107ee657e7e4b6ee7b98cae643ce06bea7090';
const git=(...args)=>execFileSync('git',args,{encoding:'utf8'}).trim();
