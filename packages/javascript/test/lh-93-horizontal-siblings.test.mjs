// LH-93 remainder: horizontal bar charts of one unit side by side share one plot (one height, and one width, so one value is one bar
// length on both); a chart with options or stacked marks keeps its own.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { composeSlide } from '../dist/composition.js';

const bar = (rows, extra = {}) => ({ chart: { type: 'bar', data: { columns: ['Stage', 'Deals'], rows }, ...extra } });
const slide = (a, b) => ({ title: 'Pipeline by stage', layout: 'two-column', blocks: [a, b] });
const charts = (s) => composeSlide(s, { width: 1280, height: 720 }).items.filter((item) => item.field === 'chart');
const plotOf = (item) => { const p = item.chart.layer.plot; return { x: item.box.x + p.left, y: item.box.y + p.top, width: item.box.width - p.left - p.right, height: item.box.height - p.top - p.bottom }; };

test('two horizontal bar charts side by side share one plot height and width', () => {
	const items = charts(slide(bar([['Lead', 120], ['Qualified', 64], ['Won', 12]]), bar([['Lead generated by partners', 96], ['Qualified by sales', 52], ['Won', 9]])));
	assert.equal(items.length, 2);
	assert.ok(items.every((item) => item.chart.layer?.plot), 'both pinned');
	const [a, b] = items.map(plotOf);
	assert.ok(Math.abs(a.width - b.width) < 1e-6, `one width (${a.width}, ${b.width})`);
	assert.ok(Math.abs(a.height - b.height) < 1e-6 && Math.abs(a.y - b.y) < 1e-6, 'one height, one top');
	assert.deepEqual(items[0].chart.valueAxis, items[1].chart.valueAxis, 'one value axis (LH-33)');
	// Each plot stays inside its chart box, after its own category gutter.
	for (const [item, plot] of [[items[0], a], [items[1], b]]) assert.ok(plot.x > item.box.x && plot.x + plot.width < item.box.x + item.box.width);
});

test('a chart with options keeps its own plot, and so does its sibling', () => {
	const items = charts(slide(bar([['Lead', 120], ['Won', 12]], { legend: 'bottom' }), bar([['Lead', 96], ['Won', 9]])));
	assert.ok(items.every((item) => item.chart.layer?.plot === undefined));
});
