#!/usr/bin/env node
// Writes src/prior-layout-hashes.ts: for each layout id of the current gallery and each gallery layout OPF 0.35 removed (flow,
// vertical-flow, agenda-split), the hash of every version of its record released before OPF 0.35, as `opf embed` copied it into a
// deck (no `$schema`, `id` or `x-*`): the first 16 hex digits of core's documentHash. The versions are read from the git history of
// packages/gallery/catalog/layouts/ up to v0.34.2, the last release before the 0.35 layout simplification, so the table is fixed:
// rerun it only to add the versions of a later release whose records a later schema rejects.
//
//   node packages/javascript/scripts/prior-layout-hashes.mjs        (from the repository root, after building core)
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LAST = 'v0.34.2';
const RELEASES_034 = ['v0.34.0', 'v0.34.1', 'v0.34.2'];
const REMOVED = ['flow', 'vertical-flow', 'agenda-split'];
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const { documentHash } = await import(pathToFileURL(path.join(root, 'packages/javascript/dist/index.js')).href);
const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', maxBuffer: 1 << 28 });
const dir = 'packages/gallery/catalog/layouts';
const current = readdirSync(path.join(root, dir)).filter((file) => file.endsWith('.json') && file !== 'index.json').map((file) => file.slice(0, -5));
const wanted = new Set([...current, ...REMOVED]);
const embedded = (record) => Object.fromEntries(Object.entries(record).filter(([key]) => key !== '$schema' && key !== 'id' && !key.startsWith('x-')));
const hashOf = (record) => documentHash(embedded(record)).slice('sha256:'.length, 'sha256:'.length + 16);

/** The hash of each wanted record in the layouts directory at `commit`, added to `into` (id to set of hashes). */
const collect = (commit, into) => {
  for (const file of git('ls-tree', '--name-only', `${commit}:${dir}/`).trim().split('\n')) {
    const id = file.replace(/\.json$/, '');
    if (!file.endsWith('.json') || !wanted.has(id)) continue;
    if (!into.has(id)) into.set(id, new Set());
    into.get(id).add(hashOf(JSON.parse(git('show', `${commit}:${dir}/${file}`))));
  }
};
const prior = new Map();
for (const commit of git('log', '--format=%H', LAST, '--', `${dir}/`).trim().split('\n')) collect(commit, prior);
const released = new Map();
for (const tag of RELEASES_034) collect(tag, released);

const table = (map) =>
  [...map]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([id, set]) => `  ${JSON.stringify(id)}: [${[...set].sort().map((hash) => `'${hash}'`).join(', ')}],`)
    .join('\n');
const text = `// Generated by packages/javascript/scripts/prior-layout-hashes.mjs from the git history of ${dir}/ up to ${LAST}. Do not edit.
/**
 * OPF 0.35: every version of the gallery's built-in layout records released before 0.35, by id, as \`opf embed\` copied it into a deck
 * (no \`$schema\`, \`id\` or \`x-*\`): the first 16 hex digits of its documentHash. An embedded copy whose hash is listed for its id is an
 * unedited built-in record (stale-records.ts).
 */
export const PRIOR_LAYOUT_HASHES: Readonly<Record<string, readonly string[]>> = {
${table(prior)}
};

/**
 * The versions OPF 0.34 released (v0.34.0 to v0.34.2): 0.35 converted exactly these records, so the current record draws as such a
 * copy did, and taking it (\`use-current-record\`) is safe.
 */
export const RELEASE_034_LAYOUT_HASHES: Readonly<Record<string, readonly string[]>> = {
${table(released)}
};
`;
writeFileSync(path.join(root, 'packages/javascript/src/prior-layout-hashes.ts'), text);
console.log(`${prior.size} ids, ${[...prior.values()].reduce((sum, set) => sum + set.size, 0)} versions; 0.34: ${[...released.values()].reduce((sum, set) => sum + set.size, 0)}`);
