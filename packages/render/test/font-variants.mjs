import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {create} from 'fontkit';
import {prepareNodeFonts} from '../dist/fonts-node.js';
import {createFontRegistry} from '../dist/fonts.js';

const {registry,options}=await prepareNodeFonts();
const entries=options.embeddedFonts.map(face=>({...face,data:Uint8Array.from(Buffer.from(face.dataUrl.split(',')[1],'base64'))}));
const report={node:process.version,faces:[],guards:[]},text='Office AVATAR 0123 — typography';
for(const [index,entry]of entries.entries()){
  const bytes=await readFile(options.fontFiles[index]),font=create(bytes);
  const group=font.getName('preferredFamily','en')??font.familyName;
  const requested={fontFamily:group,fontWeight:entry.weight,italic:!!entry.italic,path:`faces.${index}`};
  const resolution=registry.resolveFont(requested),style=registry.textMeasurement.resolveStyle(requested);
  const physical={family:font.getName('fontFamily','en'),bold:font['OS/2'].fsSelection.bold,italic:font['OS/2'].fsSelection.italic};
  assert.equal(resolution.resolvedFamily,entry.family);
  assert.equal(resolution.resolvedWeight,entry.weight);
  assert.equal(resolution.compatibility,'exact');
  assert.equal(resolution.path,requested.path);
  assert.deepEqual(resolution.fontFace,physical);
  assert.deepEqual(style.fontFace,physical);
  const single=createFontRegistry([entry]),exactStyle={...requested,fontFamily:entry.family};
  assert.equal(registry.textMeasurement.measure(text,42,requested),single.textMeasurement.measure(text,42,exactStyle));
  assert.deepEqual(registry.textMeasurement.outlineBounds(text,42,requested),single.textMeasurement.outlineBounds(text,42,exactStyle));
  style.fontFace.family='Mutated return value';resolution.fontFace.bold=!physical.bold;
  assert.deepEqual(registry.resolveFont(requested).fontFace,physical,'Returned metadata must not mutate registered face selection');
  assert.deepEqual(registry.resolveFont(exactStyle).fontFace,physical,'Legacy family requests stay valid');
  report.faces.push({requested,resolvedFamily:entry.family,physical,sha256:createHash('sha256').update(bytes).digest('hex')});
}
const custom=createFontRegistry(entries.map(entry=>({...entry,family:`Custom ${entry.family}`})));
assert.throws(()=>custom.resolveFont({fontFamily:'Roboto',fontWeight:500}),{code:'font-unavailable'});
assert.equal(custom.resolveFont({fontFamily:'Custom Roboto Medium',fontWeight:500}).fontFace.family,'Roboto Medium');
report.guards.push('Explicit custom family overrides do not expose preferred-family aliases');
const aliases=createFontRegistry(entries,{aliases:{'User Sans':'Roboto'}});
const aliased=aliases.resolveFont({fontFamily:'User Sans',fontWeight:600});
assert.equal(aliased.resolvedWeight,600);assert.equal(aliased.compatibility,'visual');
report.guards.push('Explicit user alias finds the exact available weight while remaining a visual mapping');
const medium=entries.find(face=>face.weight===500);
assert.throws(()=>createFontRegistry([...entries,{...medium,family:'Roboto'}]),{code:'ambiguous-font-face'});
assert.throws(()=>createFontRegistry([...entries,medium]),{code:'duplicate-font-face'});
report.guards.push('Ambiguous grouped faces and identical duplicate slots reject');
const approximate=registry.resolveFont({fontFamily:'Roboto',fontWeight:300});
assert.equal(approximate.resolvedWeight,400);assert.equal(approximate.compatibility,'visual');
assert.equal(registry.resolveFont({fontFamily:'Roboto',fontWeight:500,italic:true}).compatibility,'visual');
report.guards.push('Unavailable weights remain explicit approximations without synthetic styles');
const output=path.resolve(process.argv[2]??'artifacts/font-variants.json');
await mkdir(path.dirname(output),{recursive:true});await writeFile(output,JSON.stringify(report,null,2)+'\n');
console.log('Nine exact grouped faces preserve measured bytes and physical style links; overrides, aliases, duplicates and approximation controls pass.');
