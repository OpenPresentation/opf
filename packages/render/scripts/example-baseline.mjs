// Ordinary examples retain exact baselines for both known core metric-default contracts.
import assert from 'node:assert/strict';

export const LEGACY_EXAMPLE_BASELINE = 'test/golden/opf-examples-png.rr20-array-areas.sha256.json';
export const CENTERED_EXAMPLE_BASELINE = 'test/golden/opf-examples-png.rr85-metric-centering.sha256.json';
// RR-90/91/93 (core 0.22): the first-use layout (table text at the body size, footer zones on the content inset). The reviewed
// rr85 fixture keeps its exact bytes (test/example-baseline.mjs); this one is regenerated for core 0.22 by `regenerate-goldens`.
export const FIRST_USE_EXAMPLE_BASELINE = 'test/golden/opf-examples-png.rr90-first-use-layout.sha256.json';
// RR-89/90/92 (core 0.22): the chart contract (series from the colour scheme, 20 px chart text, core's value axis). Started as a copy of
// the first-use baseline and regenerated by `regenerate-goldens`; the first-use baseline keeps its bytes.
export const CHART_EXAMPLE_BASELINE = 'test/golden/opf-examples-png.rr89-chart-palette-text.sha256.json';
// RR-96 (core 0.23): scheme-derived neutrals (borders, gridlines and axis lines from the scheme) and the color-variants example. A new
// baseline written by the regenerate workflows; the chart baseline keeps its bytes.
export const SCHEME_NEUTRALS_EXAMPLE_BASELINE = 'test/golden/opf-examples-png.rr96-scheme-neutrals.sha256.json';
// RR-96 (renderer step 2): slides drawn from core's variant roles (background, text, neutrals, accent order, picture tone). Started as a copy
// of the scheme-neutrals baseline and regenerated by `regenerate-goldens`; the scheme-neutrals baseline keeps its bytes.
export const VARIANTS_EXAMPLE_BASELINE_CORE_023 = 'test/golden/opf-examples-png.rr96-color-variants.sha256.json';
// RR-96 (core 0.24, gallery 4.0.0): the same variant contract over the gallery 4 example corpus (the `dark` theme is gone, so 25 decks moved to
// `classic`, and every embedded theme record gained `variants`). Started as a copy of the core 0.23 baseline and regenerated by
// `regenerate-goldens`; the core 0.23 baseline keeps its bytes. Notes: test/golden/notes/RR-96-baseline-core-024.md.
export const VARIANTS_EXAMPLE_BASELINE = 'test/golden/opf-examples-png.rr96-gallery-4.sha256.json';
/** The chart text size (px) of core before RR-90: 14 px floored to the 16 px minimum. */
export const LEGACY_CHART_TEXT_SIZE = 16;
/** The table cell size (px) of core before RR-90, which asked for 15 px and was floored to 16 px. */
export const LEGACY_TABLE_TEXT_SIZE = 16;

export function exampleBaseline(alignment, tableSize = LEGACY_TABLE_TEXT_SIZE, chartSize = LEGACY_CHART_TEXT_SIZE, neutrals = false, variants = false) {
  assert.ok(alignment === 'left' || alignment === 'center', `Unknown metric default alignment: ${alignment}`);
  assert.ok(Number.isFinite(tableSize) && tableSize > 0, `Unknown table text size: ${tableSize}`);
  assert.ok(Number.isFinite(chartSize) && chartSize > 0, `Unknown chart text size: ${chartSize}`);
  if (alignment === 'left') return LEGACY_EXAMPLE_BASELINE;
  if (tableSize > LEGACY_TABLE_TEXT_SIZE) return chartSize > LEGACY_CHART_TEXT_SIZE ? (neutrals ? (variants ? VARIANTS_EXAMPLE_BASELINE : SCHEME_NEUTRALS_EXAMPLE_BASELINE) : CHART_EXAMPLE_BASELINE) : FIRST_USE_EXAMPLE_BASELINE;
  return CENTERED_EXAMPLE_BASELINE;
}
