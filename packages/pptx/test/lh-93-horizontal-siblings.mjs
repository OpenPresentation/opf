// LH-93 remainder in the PPTX export: horizontal bar siblings write core's shared plot as the plot area's inner manual layout, so
// PowerPoint draws one value as one bar length on both charts, as the preview does.
import assert from 'node:assert/strict';
import {unzipSync, strFromU8} from 'fflate';
import {toPptx} from '../dist/index.js';

const bar = rows => ({chart: {type: 'bar', data: {columns: ['Stage', 'Deals'], rows}}});
const deck = {slides: [{title: 'Pipeline by stage', layout: 'two-column', blocks: [bar([['Lead', 120], ['Qualified', 64], ['Won', 12]]), bar([['Lead generated by partners', 96], ['Qualified by sales', 52], ['Won', 9]])]}]};
const parts = unzipSync(await toPptx(deck));
const slide = strFromU8(parts['ppt/slides/slide1.xml']);
const frames = [...slide.matchAll(/<p:graphicFrame>[\s\S]*?<a:off x="(\d+)" y="(\d+)"\/><a:ext cx="(\d+)" cy="(\d+)"\/>[\s\S]*?<c:chart r:id="(rId\d+)"/g)].map(m => ({x: +m[1], y: +m[2], w: +m[3], h: +m[4]}));
assert.equal(frames.length, 2);
const plots = [1, 2].map((n, index) => {
  const xml = strFromU8(parts[`ppt/charts/chart${n}.xml`]);
  const layout = /<c:plotArea><c:layout><c:manualLayout><c:layoutTarget val="inner"\/><c:xMode val="edge"\/><c:yMode val="edge"\/><c:x val="([\d.]+)"\/><c:y val="([\d.]+)"\/><c:w val="([\d.]+)"\/><c:h val="([\d.]+)"\/>/.exec(xml);
  assert.ok(layout, `chart ${n}: the plot is pinned (inner)`);
  const frame = frames[index];
  return {w: Number(layout[3]) * frame.w, h: Number(layout[4]) * frame.h, y: frame.y + Number(layout[2]) * frame.h};
});
const tolerance = 9525 * 1.5; // the fractions are written to four decimals
assert.ok(Math.abs(plots[0].w - plots[1].w) < tolerance, `one plot width (${plots[0].w}, ${plots[1].w} EMU)`);
assert.ok(Math.abs(plots[0].h - plots[1].h) < tolerance && Math.abs(plots[0].y - plots[1].y) < tolerance, 'one plot height and top');
console.log('LH-93: horizontal bar siblings pin one shared plot in PowerPoint.');
