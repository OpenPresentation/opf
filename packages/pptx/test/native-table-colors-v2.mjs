import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {zipSync, strToU8} from 'fflate';
import {spawnSync} from 'node:child_process';
import {windowsPowerShellEnvironment} from '../../../scripts/native-acceptance/windows-powershell-env.mjs';
import {tableColorDocument} from '../../../scripts/native-acceptance/table-colors.mjs';
const own=path.dirname(fileURLToPath(import.meta.url)),worker=path.join(own,'native-table-colors-v2.ps1');
const source=fs.readFileSync(worker,'utf8');
assert.match(source,/\[switch\]\$Worker/u);
assert.match(source,/Only the reviewed table-profile supervisor may launch this worker/u);
assert.equal((source.match(/New-Object -ComObject PowerPoint\.Application/gu)??[]).length,1);
assert.equal((source.match(/\.Presentations\.Open\(/gu)??[]).length,1);
assert.match(source,/\.Presentations\.Open\(\$Path,-1,0,0\)/u);
assert.equal((source.match(/\.SaveCopyAs\(/gu)??[]).length,1);
assert.equal((source.match(/\.Close\(\)/gu)??[]).length,1);
assert.equal((source.match(/\.Quit\(\)/gu)??[]).length,1);
assert.doesNotMatch(source,/Stop-Process|GetActiveObject|ActivePresentation|\.SaveAs\(|\.Visible\s*=/u);
assert.match(source,/if\(\$script:stopped\) \{ throw 'Table Office operations stopped after failure'/u);
assert.match(source,/Deliberately no finally\/cleanup Office calls after a failure/u);
assert.match(fs.readFileSync(path.join(own,'native-table-colors.ps1'),'utf8'),/^param[^\n]*\r?\n[^\n]*\r?\nthrow 'Retired unsafe native helper/u);
const wrapper=fs.readFileSync(path.join(own,'../../../scripts/native-acceptance/run-table-profile.ps1'),'utf8');
assert.match(wrapper,/\[ValidateRange\(5,60\)\]/u);
assert.equal((wrapper.match(/Invoke-OpfNativeWorker -ScriptPath/gu)??[]).length,1,'Exactly one supervisor launch');
if(process.platform==='win32'){
 const parent=process.env.OPF_NATIVE_TABLE_TEST_OUTPUT;
 const scratch=parent?fs.mkdtempSync(path.join(parent,'pure-')):fs.mkdtempSync(path.join(os.tmpdir(),'opf-table-v2-'));
 try{
  const generation=path.join(scratch,'generation.json'),report=path.join(scratch,'controls.json');
  fs.writeFileSync(generation,JSON.stringify(tableColorDocument()));
  const archiveDirectory=path.join(scratch,'archives');fs.mkdirSync(archiveDirectory);
  const xml='<a:root xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><a:tbl><a:tblGrid><a:gridCol/><a:gridCol/></a:tblGrid><a:tr><a:tc/><a:tc/></a:tr><a:tr><a:tc/><a:tc/></a:tr></a:tbl></a:root>';
  const parts=()=>Object.fromEntries(Array.from({length:6},(_,i)=>[`ppt/slides/slide${i+1}.xml`,strToU8(xml)]));
  const cases=[];
  const put=(file,entries,pass,message='')=>{fs.writeFileSync(path.join(archiveDirectory,file),Buffer.isBuffer(entries)?entries:zipSync(entries));cases.push({file,pass,message});};
  put('positive.pptx',parts(),true);
  let p=parts();delete p['ppt/slides/slide6.xml'];put('five.pptx',p,false,'exactly six');
  p=parts();p['ppt/slides/slide7.xml']=strToU8(xml);put('seven.pptx',p,false,'exactly six');
  p=parts();p['ppt/slides/slide1.xml']=strToU8(xml.replace('<a:tbl>','<a:tbl/><a:tbl>'));put('two-tables.pptx',p,false,'one two-by-two');
  p=parts();p['ppt/slides/slide1.xml']=strToU8(xml.replace('<a:tblGrid>','<a:tblGrid><a:gridCol/>'));put('three-columns.pptx',p,false,'one two-by-two');
  p=parts();p['ppt/slides/slide1.xml']=strToU8(xml.replace('<a:tr>','<a:tr><a:tc/>'));put('three-cells.pptx',p,false,'row requires two');
  p=parts();p['ppt/slides/slide1.xml']=strToU8('<!DOCTYPE a:root [<!ENTITY x "unsafe">]>'+xml);put('doctype.pptx',p,false);
  p=parts();p['ppt/slides/slide1.xml']=strToU8('<malformed');put('malformed.pptx',p,false);
  p=parts();p['../escape']=strToU8('x');put('traversal.pptx',p,false,'unsafe table ZIP');
  p=parts();for(let i=0;i<4097;i++)p['extra-'+i]=new Uint8Array();put('entry-count.pptx',p,false,'4096 entries');
  put('size.pptx',Buffer.alloc(16777217),false,'16 MiB');
  fs.writeFileSync(path.join(archiveDirectory,'cases.json'),JSON.stringify(cases));
  const shell=path.join(process.env.WINDIR,'System32/WindowsPowerShell/v1.0/powershell.exe');
  const result=spawnSync(shell,['-NoProfile','-NonInteractive','-File',path.join(own,'native-table-colors-v2-check.ps1'),'-WorkerPath',worker,'-GenerationFile',generation,'-ReportPath',report,'-ArchiveDirectory',archiveDirectory],{encoding:'utf8',timeout:60000,windowsHide:true,env:windowsPowerShellEnvironment(process.env)});
  fs.writeFileSync(path.join(scratch,'stdout.log'),result.stdout??'');fs.writeFileSync(path.join(scratch,'stderr.log'),result.stderr??'');
  assert.equal(result.error,undefined);assert.equal(result.status,0,result.stdout+result.stderr);
  const controls=JSON.parse(fs.readFileSync(report,'utf8').replace(/^\uFEFF/u,''));
  assert.equal(controls.passed,true);assert.equal(controls.cases.length,52+cases.length+1+8+2+3+2);
  assert.ok(controls.cases.every(item=>item.passed));
  console.log(`Actual-source pure PowerShell table lifecycle: ${controls.cases.length} controls PASS; ${scratch}`);
 }finally{if(!parent)fs.rmSync(scratch,{recursive:true,force:true});}
}else console.log('Windows PowerShell managed-object controls require Windows; static source controls PASS.');
