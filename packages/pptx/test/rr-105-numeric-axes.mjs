import assert from 'node:assert/strict';
import fs from 'node:fs';
import { strFromU8, unzipSync } from 'fflate';
import { toPptx } from '../dist/index.js';
import { gallery } from '@openpresentation/gallery';
const document = JSON.parse(fs.readFileSync(new URL('../../../examples/technical/chart-type-sampler.opf.json', import.meta.url), 'utf8'));
document.slides = document.slides.slice(0, 1);
const entries = unzipSync(new Uint8Array(await toPptx(document, {catalogs: [gallery]})));
const xml = Object.fromEntries(Object.entries(entries).filter(([name]) => /^ppt\/charts\/chart(?:Ex)?\d+\.xml$/.test(name)).map(([name, bytes]) => [name, strFromU8(bytes)]));
const box = Object.values(xml).find(value => value.includes('layoutId="boxWhisker"'));
assert.ok(box);
assert.match(box, /<cx:valScaling max="15" min="0" majorUnit="5"\/>/);
const scatter = Object.values(xml).find(value => value.includes('<c:scatterChart>'));
assert.ok(scatter);
const axes = [...scatter.matchAll(/<c:valAx>([\s\S]*?)<\/c:valAx>/g)].map(match => match[1]);
const numeric = axis => ({min: Number(/<c:min val="([^"]+)"/.exec(axis)?.[1]), max: Number(/<c:max val="([^"]+)"/.exec(axis)?.[1]), majorUnit: Number(/<c:majorUnit val="([^"]+)"/.exec(axis)?.[1])});
const x = axes.find(axis => axis.includes('<c:axPos val="b"'));
const y = axes.find(axis => axis.includes('<c:axPos val="l"'));
assert.deepEqual(numeric(x), {min: 0, max: 500, majorUnit: 100});
assert.deepEqual(numeric(y), {min: 0, max: 250, majorUnit: 100});
assert.ok(!x.includes('<c:majorGridlines>'), 'preview has no vertical X gridlines');
assert.ok(y.includes('<c:majorGridlines>'), 'horizontal value gridlines remain');
console.log('RR-105: exact native box and scatter axes match the preview');
