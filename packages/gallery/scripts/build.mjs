#!/usr/bin/env node
// Builds @openpresentation/gallery's dist/ from the catalog records in catalog/ and the layout previews in
// previews/layouts/ (RR-78). The package has no runtime dependency: the records are inlined into dist/index.js and the
// previews into dist/previews.js, and the declarations in src/ are copied next to them.
//
//   node scripts/build.mjs
//
// From 2.0.0 the layouts in catalog/layouts/ are written here (then `npm run rehash` and `npm run previews`); the other
// kinds are the records pptx.gallery published for 1.x. previews/layouts/ is written by scripts/render-previews.mjs.
// The shape of `gallery` is the shape core resolves (`Catalog`): `source` and the eight content kinds, each record keyed
// by id without `$schema`, `id` or `x-*` members.
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalogRoot = path.join(packageRoot, "catalog");
const previewsRoot = path.join(packageRoot, "previews", "layouts");
const dist = path.join(packageRoot, "dist");

export const GALLERY_SOURCE = "https://www.pptx.gallery";

/** The content kinds a document references, in core's `catalogKinds` order, with their catalog/ directory. */
export const CONTENT_KINDS = [
  ["layouts", "layouts"],
  ["themes", "themes"],
  ["colorSchemes", "color-schemes"],
  ["fontSchemes", "font-schemes"],
  ["narratives", "narratives"],
  ["audiences", "audiences"],
  ["purposes", "purposes"],
  ["tones", "tones"],
];
/** The display kinds: picker metadata for engine vocabularies, never referenced by a document. */
export const DISPLAY_KINDS = [
  ["chartTypes", "chart-types"],
  ["languages", "languages"],
  ["socialPlatforms", "social-platforms"],
];

/** LH-14: the icon sets, one module each under dist/icon-sets/, loaded only when a deck uses one (`galleryIconSets`, dist/icon-sets.js). */
export const ICON_SETS_DIR = "icon-sets";

const readJson = async (file) => JSON.parse(await readFile(file, "utf8"));

/** The record a document embeds: no `$schema`, no `id` (the key is the id), no publisher `x-*` members. */
export function embeddedCopy(record) {
  return Object.fromEntries(Object.entries(record).filter(([key]) => key !== "$schema" && key !== "id" && !key.startsWith("x-")));
}

/** Reads catalog/<dir>/index.json and its records in index order. */
export async function readKind(root, dir) {
  const index = await readJson(path.join(root, dir, "index.json"));
  const records = [];
  for (const entry of index.records) records.push(await readJson(path.join(root, dir, entry.file)));
  return { index, records };
}

/** Everything dist/index.js exports, as plain data. */
export async function readCatalog(root = catalogRoot) {
  const keyed = (records) => Object.fromEntries(records.map((record) => [record.id, embeddedCopy(record)]));
  const gallery = { source: GALLERY_SOURCE };
  const display = {};
  const indexes = {};
  for (const [key, dir] of CONTENT_KINDS) {
    const { index, records } = await readKind(root, dir);
    gallery[key] = keyed(records);
    indexes[key] = index;
  }
  for (const [key, dir] of DISPLAY_KINDS) {
    const { index, records } = await readKind(root, dir);
    display[key] = keyed(records);
    indexes[key] = index;
  }
  const { index: iconIndex, records: iconRecords } = await readKind(root, ICON_SETS_DIR);
  indexes.iconSets = iconIndex;
  const manifest = await readJson(path.join(root, "manifest.json"));
  return { gallery, display, indexes, manifest, iconSets: keyed(iconRecords) };
}

const literal = (value) => `JSON.parse(${JSON.stringify(JSON.stringify(value))})`;

export async function build() {
  const pkg = await readJson(path.join(packageRoot, "package.json"));
  const catalogSchema = pkg.opf?.catalogSchema;
  if (!Number.isInteger(catalogSchema)) throw new Error("package.json opf.catalogSchema must be an integer");
  const { gallery, display, indexes, manifest, iconSets } = await readCatalog();
  // LH-14: each icon set is a module of its own that `galleryIconSets` (a separate entry) imports the first time a deck uses the set (ensureIcons
  // calls it): `gallery` names none of them, so a host that does not register the icon sets carries none of their data.
  const loaders = Object.keys(iconSets)
    .map((id) => `  ${JSON.stringify(id)}: () => import("./${ICON_SETS_DIR}/${id}.js").then((module) => module.default),`)
    .join("\n");
  if (manifest.publisher !== GALLERY_SOURCE) throw new Error(`catalog/manifest.json publisher is ${manifest.publisher}, expected ${GALLERY_SOURCE}`);

  const index = `// Generated by scripts/build.mjs from catalog/. Do not edit by hand.
const data = ${literal({ gallery, display, indexes, manifest })};
// Frozen to the depth core's former defaultCatalog was: the catalog, each kind and each record. A record's nested values
// are not, so an engine that reads them behaves exactly as with that object.
const freeze = (value, depth) => {
  if (depth > 0 && value && typeof value === "object") {
    for (const child of Object.values(value)) freeze(child, depth - 1);
    Object.freeze(value);
  }
  return value;
};
/** The source the gallery is registered under, and the \`source\` of a document's \`catalogs.default\`. */
export const GALLERY_SOURCE = ${JSON.stringify(GALLERY_SOURCE)};
/** The version of core's catalog record schemas these records target (package.json \`opf.catalogSchema\`). */
export const CATALOG_SCHEMA = ${catalogSchema};
/** The pptx.gallery catalog: register it with \`catalogs: [gallery]\` (and \`galleryIconSets\` of \`@openpresentation/gallery/icon-sets\` for icons). */
export const gallery = freeze(data.gallery, 3);
/** Display metadata for pickers: chart types, languages and social platforms by id. */
export const catalogDisplay = freeze(data.display, 3);
/** Each kind's \`index.json\`: the record summaries and their content hash. */
export const catalogIndexes = freeze(data.indexes, 1);
/** The pptx.gallery commit these records were synced from, and a content hash per kind. */
export const catalogManifest = freeze(data.manifest, 1);
`;

  const previewIndex = await readJson(path.join(previewsRoot, "index.json"));
  const previews = {};
  for (const record of previewIndex.records) {
    // The renderer ends each file with a newline; the string keeps the fragment only.
    previews[record.id] = (await readFile(path.join(previewsRoot, record.file), "utf8")).replace(/\n$/, "");
  }
  const previewsJs = `// Generated by scripts/build.mjs from previews/layouts/. Do not edit by hand.
const data = ${literal({ previews, index: previewIndex })};
/** The SVG preview of each layout, keyed by the layout id: a self-contained <svg> element with a 16:9 viewBox. */
export const layoutPreviews = Object.freeze(data.previews);
/** The preview index: the slugs, their files and byte counts. */
export const layoutPreviewIndex = Object.freeze(data.index);
/** The id of every layout that ships a preview, sorted. */
export const layoutPreviewSlugs = Object.freeze(Object.keys(data.previews).sort());
/** Whether a preview exists for the layout id. */
export function hasLayoutPreview(slug) {
  return Object.hasOwn(data.previews, slug);
}
/** The SVG preview of a layout id, or undefined when none ships. */
export function getLayoutPreview(slug) {
  return Object.hasOwn(data.previews, slug) ? data.previews[slug] : undefined;
}
`;

  // Only files whose bytes change are written, and only stale ones removed, so a build that runs beside another (the
  // CI job builds once and its parallel steps call `build` again) never leaves dist/ empty or half written.
  const iconSetsJs = `// Generated by scripts/build.mjs from catalog/icon-sets/. Do not edit by hand.
/**
 * LH-14: the gallery's icon sets as a catalog to register beside \`gallery\` (\`catalogs: [gallery, galleryIconSets]\`): each set is a
 * function that imports its module (\`@openpresentation/gallery/icon-sets/<id>\`) the first time a deck uses it; core's ensureIcons calls it.
 */
export const galleryIconSets = Object.freeze({ source: ${JSON.stringify(GALLERY_SOURCE)}, iconSets: Object.freeze({
${loaders}
}) });
`;
  const files = {
    "index.js": index,
    "icon-sets.js": iconSetsJs,
    "icon-sets.d.ts": await readFile(path.join(packageRoot, "src", "icon-sets.d.ts"), "utf8"),
    "previews.js": previewsJs,
    "index.d.ts": await readFile(path.join(packageRoot, "src", "index.d.ts"), "utf8"),
    "previews.d.ts": await readFile(path.join(packageRoot, "src", "previews.d.ts"), "utf8"),
    [`${ICON_SETS_DIR}/icon-set.d.ts`]: await readFile(path.join(packageRoot, "src", "icon-set.d.ts"), "utf8"),
  };
  for (const [id, record] of Object.entries(iconSets)) {
    files[`${ICON_SETS_DIR}/${id}.js`] = `// Generated by scripts/build.mjs from catalog/icon-sets/${id}.json (written by scripts/build-icon-sets.mjs). Do not edit by hand.
// ${record.name} ${record.version}, ${record.license}: ${record.copyright}. The full license is the record's licenseText and THIRD-PARTY-NOTICES.md.
/** The ${record.name} icon set: an https://openpresentation.org/schema/opf-icon-set/v1 record without $schema and id. */
export default Object.freeze(${literal(record)});
`;
  }
  await mkdir(path.join(dist, ICON_SETS_DIR), { recursive: true });
  for (const name of await readdir(dist)) if (name !== ICON_SETS_DIR && !(name in files) && !name.endsWith(".tmp")) await rm(path.join(dist, name), { recursive: true, force: true });
  for (const name of await readdir(path.join(dist, ICON_SETS_DIR))) if (!(`${ICON_SETS_DIR}/${name}` in files) && !name.endsWith(".tmp")) await rm(path.join(dist, ICON_SETS_DIR, name), { force: true });
  for (const [name, text] of Object.entries(files)) {
    const target = path.join(dist, name);
    if (existsSync(target) && (await readFile(target, "utf8")) === text) continue;
    const temporary = `${target}.${process.pid}.tmp`;
    await writeFile(temporary, text);
    await rename(temporary, target);
  }
  const count = Object.values(gallery).reduce((sum, records) => sum + (typeof records === "object" ? Object.keys(records).length : 0), 0);
  return { records: count, previews: previewIndex.records.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { records, previews } = await build();
  process.stdout.write(`Built @openpresentation/gallery: ${records} content records, ${previews} layout previews.\n`);
}
